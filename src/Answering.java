    private void updateTimer() {
    int minutes = timeLeft / 60;
    int seconds = timeLeft % 60;

    lblTimer.setText(String.format(
            "%02d:%02d", minutes, seconds));
}

private void startTimer() {
    timeLeft = 60;
    updateTimer();

    if (quizTimer != null) {
        quizTimer.stop();
    }

    quizTimer = new javax.swing.Timer(1000, e -> {
        timeLeft--;
        updateTimer();

        if (timeLeft <= 0) {
        quizTimer.stop();
        JOptionPane.showMessageDialog(this, "Time ran out!", "Time's Up", JOptionPane.INFORMATION_MESSAGE);
        btnNext.doClick();
    }
});

quizTimer.start();
}
