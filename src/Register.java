    private void btnCreateAccountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateAccountActionPerformed
    String studentID = txtStudentID.getText().trim();
    String password = new String(txtPassword.getPassword());
    String rePassword = new String(txtRePassword.getPassword());

    if (studentID.isEmpty() || password.isEmpty() || rePassword.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all fields!");
        return;
    }
    if (!password.equals(rePassword)) {
        JOptionPane.showMessageDialog(this, "Passwords do not match!");
        return;
    }

    DBConn db = new DBConn();

    if (db.usernameExists(studentID)) {
        JOptionPane.showMessageDialog(this, "That Student ID is already registered!");
        return;
    }

    if (db.register(studentID, password, "student")) {
        JOptionPane.showMessageDialog(this, "Account created successfully!");
        new Proceed().setVisible(true);
        this.dispose();
    } else {
        JOptionPane.showMessageDialog(this, "Registration failed. Please try again.");
    }
    }//GEN-LAST:event_btnCreateAccountActionPerformed

